export default function Info() {
  const { slug = 'about' } = useParams();
  const source = content[slug];
  const info = source
    ? { ...source, title: source.title.replaceAll('SpinPoint', siteConfig.name) }
    : undefined;
  useMeta(info?.title || 'Сторінка не знайдена');
  if (!info)
    return (
      <EmptyState
        title="Сторінка не знайдена"
        text="Перевірте адресу або поверніться до каталогу."
      />
    );
  return (
    <div className="container page info-page">
      <Breadcrumbs items={[{ label: info.title }]} />
      <div className="info-header">
        <span className="eyebrow blue-text">{siteConfig.name.toUpperCase()} / ІНФОРМАЦІЯ</span>
        <h1>
          {info.title}
          <span className="blue-text">.</span>
        </h1>
        <p>{info.intro}</p>
      </div>
      <div className="info-layout">
        <aside>
          <h3>Покупцеві</h3>
          {Object.entries(content).map(([key, v]) => (
            <Link className={slug === key ? 'active' : ''} key={key} to={`/info/${key}`}>
              {v.title.replaceAll('SpinPoint', siteConfig.name)}
              <ArrowUpRight size={15} />
            </Link>
          ))}
        </aside>
        <article>
          {info.sections.map(([heading, original]) => {
            const configured = !!(
              siteConfig.contacts.telegramUsername ||
              siteConfig.contacts.viberPhone ||
              siteConfig.contacts.email ||
              siteConfig.contacts.phone
            );
            const text =
              slug === 'contacts' && heading === 'Зв’язок з менеджером' && configured
                ? siteConfig.viberEnabled
                  ? 'Оберіть зручний канал зв’язку нижче. Перед надсиланням перевірте одержувача.'
                  : 'Напишіть нам у Telegram. Viber тимчасово недоступний.'
                : original;
            return (
              <section key={heading}>
                <h2>{heading}</h2>
                <p>{text.replaceAll('SpinPoint', siteConfig.name)}</p>
              </section>
            );
          })}
          {slug === 'contacts' && (
            <div className="button-row">
              {siteConfig.contacts.telegramUsername ? (
                <a
                  className="button primary"
                  href={telegramUrl('Вітаю! Потрібна консультація щодо інвентарю.')}
                  target="_blank"
                  rel="noreferrer"
                >
                  <Send size={17} />
                  Telegram @{siteConfig.contacts.telegramUsername}
                </a>
              ) : !siteConfig.contacts.viberPhone &&
                !siteConfig.contacts.email &&
                !siteConfig.contacts.phone ? (
                <div className="notice">
                  Telegram та Viber з’являться тут після налаштування контактів.
                </div>
              ) : null}
              {siteConfig.viberEnabled && siteConfig.contacts.viberPhone && (
                <a className="button outline" href={viberUrl('Вітаю! Потрібна консультація.')}>
                  <MessageCircle size={17} />
                  Viber
                </a>
              )}
              {siteConfig.contacts.email && (
                <a className="button outline" href={`mailto:${siteConfig.contacts.email}`}>
                  <Mail size={17} />
                  {siteConfig.contacts.email}
                </a>
              )}
              {siteConfig.contacts.phone && (
                <a
                  className="button outline"
                  href={`tel:${siteConfig.contacts.phone.replace(/[^0-9+]/g, '')}`}
                >
                  {siteConfig.contacts.phone}
                </a>
              )}
            </div>
          )}
          {siteConfig.seller.legalName && (
            <section>
              <h2>Продавець</h2>
              <p>
                {siteConfig.seller.legalName}
                <br />
                {siteConfig.seller.registration}
                <br />
                {siteConfig.seller.address}
              </p>
            </section>
          )}
        </article>
      </div>
    </div>
  );
}
